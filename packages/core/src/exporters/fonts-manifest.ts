/**
 * The shared fonts folder: `fonts.json` and URL resolution. Public (exported from the package
 * index) so the UI's `@font-face` wiring and the PDF exporter pick fonts the same way — one
 * source of truth for families, weights and file names.
 *
 * Small and dependency-free: no font bytes, no shaper. Font files are only requested by
 * callers (the PDF exporter on its first export, the UI via `@font-face`).
 *
 * Folder layout (default: `<package>/assets/fonts/`, shipped with the package):
 *
 *   fonts.json  [{ "family": "Cairo", "weight": 400, "style": "normal",
 *                  "ttf": "Cairo-Regular.ttf", "woff2": "Cairo-Regular.woff2" }, …]
 *   *.ttf       PDF embedding (committed)
 *   *.woff2     UI (generated by scripts/subset-fonts.py --woff2; provided by the UI PR)
 *
 * File names are relative to the folder. `fontsBaseUrl` may be:
 *   - `file://…` (Node): read from disk with `node:fs` — offline, no `fetch`;
 *   - `http(s)://…`: fetched;
 *   - relative (`/fonts/`, `./fonts/`): in a browser resolved against the page and fetched; in
 *     Node there is no page, so it is a filesystem path (resolved against `process.cwd()`).
 * `node:fs` / `node:url` / `node:path` are loaded with dynamic `import()` only on the Node path,
 * so browser bundles never pull them in.
 */

export interface FontManifestEntry {
  /** CSS family name, matched case-insensitively. */
  readonly family: string;
  /** CSS weight (400 regular, 700 bold). */
  readonly weight: number;
  readonly style: 'normal' | 'italic';
  /** TTF (PDF embedding), relative to the fonts folder. */
  readonly ttf: string;
  /** WOFF2 (UI `@font-face`), relative to the fonts folder. */
  readonly woff2: string;
}

export interface FontRequest {
  /** Family or CSS stack (`'"Cairo", sans-serif'`): first family the manifest has wins. */
  readonly family: string;
  /** CSS weight; default 400. The nearest available weight is used. */
  readonly weight?: number;
  /** Default `normal`; the other style is only used when the family has no face in it. */
  readonly style?: 'normal' | 'italic';
}

export interface FontUrlOptions {
  readonly format: 'ttf' | 'woff2';
  /** Fonts folder; default {@link DEFAULT_FONTS_BASE_URL}. */
  readonly fontsBaseUrl?: string;
}

/** Families of the PDF fallback chain (always in the bundled manifest). */
export const FALLBACK_ARABIC_FAMILY = 'Noto Sans Arabic';
export const FALLBACK_LATIN_FAMILY = 'Noto Sans';

/**
 * URL of the bundled fonts folder (`<package>/assets/fonts/`, trailing slash), derived from
 * this module's URL — the same from `src/exporters/` and `dist/exporters/`. Reliable in Node
 * and when the package is served unbundled; an app bundler that moves this module should copy
 * the folder and pass its URL as `fontsBaseUrl` instead.
 */
export const DEFAULT_FONTS_BASE_URL: string = `${import.meta.url.replace(/[?#].*$/, '').replace(/\/[^/]*\/[^/]*\/[^/]*$/, '')}/assets/fonts/`;

const SAFE_PATH_RE = /^[A-Za-z0-9][A-Za-z0-9._-]*\.(ttf|woff2)$/;

/** Validate a parsed `fonts.json`. Throws with a precise message on the first problem. */
export function parseFontManifest(json: unknown): FontManifestEntry[] {
  if (!Array.isArray(json)) throw new Error('fonts.json: expected an array');
  return json.map((e: unknown, i): FontManifestEntry => {
    const at = `fonts.json[${i}]`;
    if (!e || typeof e !== 'object') throw new Error(`${at}: expected an object`);
    const o = e as Record<string, unknown>;
    if (typeof o.family !== 'string' || !o.family.trim()) throw new Error(`${at}.family: expected a non-empty string`);
    if (typeof o.weight !== 'number' || !Number.isInteger(o.weight) || o.weight < 1 || o.weight > 1000) {
      throw new Error(`${at}.weight: expected an integer 1–1000`);
    }
    if (o.style !== 'normal' && o.style !== 'italic') throw new Error(`${at}.style: expected "normal" or "italic"`);
    for (const k of ['ttf', 'woff2'] as const) {
      const v = o[k];
      // Plain file names only: no "..", no absolute paths, no URLs.
      if (typeof v !== 'string' || !SAFE_PATH_RE.test(v) || !v.endsWith(`.${k}`)) {
        throw new Error(`${at}.${k}: expected a file name ending in .${k}`);
      }
    }
    return { family: o.family, weight: o.weight, style: o.style, ttf: o.ttf as string, woff2: o.woff2 as string };
  });
}

/**
 * First family of a CSS `font-family` stack that the manifest has, as spelled in the manifest
 * (`'"cairo", sans-serif'` → `"Cairo"`). Generic and unknown families are skipped; `null`
 * when nothing matches.
 */
export function resolveFontFamily(stack: string | undefined, manifest: readonly FontManifestEntry[]): string | null {
  if (!stack) return null;
  const known = new Map(manifest.map((e) => [e.family.toLowerCase(), e.family]));
  for (const raw of stack.split(',')) {
    const name = raw.trim().replace(/^(['"])(.*)\1$/, '$2').trim().replace(/\s+/g, ' ').toLowerCase();
    const hit = name ? known.get(name) : undefined;
    if (hit) return hit;
  }
  return null;
}

/**
 * Manifest entry of `family` (exact name, case-insensitive) nearest to `weight`: the requested
 * style first, then the smallest weight distance (ties → the heavier face for weights above
 * 400, the lighter one otherwise, like CSS). `null` when the family is not in the manifest.
 */
export function pickFontEntry(
  manifest: readonly FontManifestEntry[],
  family: string,
  weight = 400,
  style: 'normal' | 'italic' = 'normal',
): FontManifestEntry | null {
  const key = family.toLowerCase();
  const cands = manifest.filter((e) => e.family.toLowerCase() === key);
  if (cands.length === 0) return null;
  const score = (e: FontManifestEntry): number =>
    (e.style === style ? 0 : 10_000) + Math.abs(e.weight - weight) * 2 + ((e.weight > weight) === (weight > 400) ? 0 : 1);
  return cands.reduce((a, b) => (score(b) < score(a) ? b : a));
}

const isNode = (): boolean => typeof process !== 'undefined' && process.versions?.node != null;

/**
 * The URL class to resolve with: Node's own in Node, so a test DOM (happy-dom, jsdom) that
 * replaces the global `URL` cannot re-base `file:` URLs onto its fake page origin.
 */
async function urlClass(): Promise<typeof URL> {
  return isNode() ? ((await import('node:url')).URL as unknown as typeof URL) : URL;
}

/** `scheme:` prefix (`file:`, `http:`, …), not a Windows drive letter (`C:\\`, `C:/`). */
const HAS_SCHEME_RE = /^[a-z][a-z\d+.-]*:/i;
const WIN_DRIVE_RE = /^[a-z]:[\\/]/i;

/**
 * Absolute folder URL (trailing slash). URLs with a scheme are used as they are; a relative
 * value resolves against the page in a browser, and against `process.cwd()` as a filesystem
 * path in Node (offline `file:` URL).
 */
export async function resolveFontsBaseUrl(fontsBaseUrl?: string): Promise<URL> {
  const U = await urlClass();
  const base = fontsBaseUrl || DEFAULT_FONTS_BASE_URL;
  const withSlash = /[\\/]$/.test(base) ? base : `${base}/`;
  if (isNode()) {
    if (HAS_SCHEME_RE.test(base) && !WIN_DRIVE_RE.test(base)) return new U(withSlash);
    const [{ pathToFileURL }, { resolve }] = await Promise.all([import('node:url'), import('node:path')]);
    const href = pathToFileURL(resolve(base)).href;
    return new U(href.endsWith('/') ? href : `${href}/`);
  }
  const loc = (globalThis as { location?: { href?: string } }).location?.href;
  return loc ? new U(withSlash, loc) : new U(withSlash);
}

/**
 * Bytes of a font-folder asset: `file:` URLs are read from disk with `node:fs` (Node only, no
 * network); `http(s)` and other URLs are fetched.
 */
export async function readFontAsset(url: URL | string): Promise<Uint8Array> {
  const u = typeof url === 'string' ? new (await urlClass())(url) : url;
  if (u.protocol === 'file:') {
    if (!isNode()) throw new Error(`Cannot read PDF font asset ${u.href}: file: URLs need Node; serve the folder over http(s)`);
    const [{ readFile }, { fileURLToPath }] = await Promise.all([import('node:fs/promises'), import('node:url')]);
    return new Uint8Array(await readFile(fileURLToPath(u)));
  }
  const res = await fetch(u.href);
  if (!res.ok) throw new Error(`Failed to load PDF font asset ${u.href}: ${res.status} ${res.statusText}`);
  return new Uint8Array(await res.arrayBuffer());
}

const manifests = new Map<string, Promise<FontManifestEntry[]>>();

/**
 * `fonts.json` of a fonts folder (default: the bundled one), validated. Cached per resolved
 * base URL; a failed load is not cached, so a later call retries.
 */
export async function loadFontManifest(fontsBaseUrl?: string): Promise<FontManifestEntry[]> {
  const base = await resolveFontsBaseUrl(fontsBaseUrl);
  let p = manifests.get(base.href);
  if (!p) {
    p = readFontAsset(`${base.href}fonts.json`).then((b) => parseFontManifest(JSON.parse(new TextDecoder().decode(b))));
    manifests.set(base.href, p);
    p.catch(() => manifests.delete(base.href));
  }
  return p;
}

/**
 * Absolute URL of the `format` file for a family/weight/style, from the folder's manifest:
 * first family of a CSS stack the manifest has (case-insensitive), nearest weight. `null`
 * when no family of the stack is in the manifest. Does not check that the file exists (the
 * woff2 files are generated by the UI build).
 */
export async function resolveFontUrl(req: FontRequest, opts: FontUrlOptions): Promise<string | null> {
  const [manifest, base] = await Promise.all([loadFontManifest(opts.fontsBaseUrl), resolveFontsBaseUrl(opts.fontsBaseUrl)]);
  const family = resolveFontFamily(req.family, manifest);
  const entry = family ? pickFontEntry(manifest, family, req.weight ?? 400, req.style ?? 'normal') : null;
  return entry ? `${base.href}${entry[opts.format]}` : null;
}
